CREATE TABLE region (
    id BIGINT NOT NULL AUTO_INCREMENT,
    code CHAR(5) NOT NULL,
    name VARCHAR(100) NOT NULL,
    province_name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_region_code UNIQUE (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE member
    ADD COLUMN primary_region_id BIGINT NULL AFTER status_message,
    ADD CONSTRAINT fk_member_primary_region FOREIGN KEY (primary_region_id)
        REFERENCES region (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

